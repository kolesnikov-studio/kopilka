/// Нарушение правила слоя данных: некорректный ввод, отсутствующая живая
/// запись, запрет на удаление из-за связанных данных и т. п.
///
/// Это не ошибка SQLite: такие отказы можно показывать пользователю.
/// [message] — техническое описание (для логов), [kind] — машиночитаемый
/// вид отказа: UI сопоставляет его с локализованным текстом (M1: RU/EN),
/// не опираясь на строки сообщений.
class DataValidationException implements Exception {
  DataValidationException(this.message, {this.kind = DataFailure.unknown});

  /// Описание нарушения (для логов и отладки).
  final String message;

  /// Вид отказа для локализованного объяснения в UI.
  final DataFailure kind;

  @override
  String toString() => 'DataValidationException: $message';
}

/// Виды отказов слоя данных, которые UI объясняет пользователю.
///
/// Группировка сознательно грубее конкретных сообщений DAO: тексты вида
/// «проверьте ввод» показываются одинаково, а отказы из-за связанных
/// данных объясняются подробно (M1: удаление — только soft delete).
enum DataFailure {
  /// Некорректные данные ввода: пустое имя, неположительная сумма,
  /// дубликат, неверная форма операции и т. п.
  invalidInput,

  /// Живая запись не найдена (уже удалена или не существует).
  notFound,

  /// Валюту используют живые счета — удалить нельзя.
  currencyUsedByAccounts,

  /// У счёта есть живые операции — удалить счёт или сменить валюту нельзя.
  accountHasTransactions,

  /// Системную категорию удалить нельзя.
  categoryIsSystem,

  /// У категории есть живые вложенные категории — удалить нельзя.
  categoryHasChildren,

  /// На категорию ссылаются живые операции — удалить нельзя.
  categoryHasTransactions,

  /// На категорию ссылается живой бюджет — удалить нельзя.
  categoryHasBudget,

  /// На категорию ссылается живой план — удалить или скрыть нельзя
  /// (v8, M7/D-128).
  categoryHasPlans,

  /// На счёт ссылается живой (ещё не исполненный) отложенный перевод —
  /// удалить нельзя (v8, M7/D-115.г).
  accountHasScheduledTransfers,

  /// На категорию комиссии ссылается живой (ещё не исполненный)
  /// отложенный перевод — удалить нельзя (v8, M7/D-115.г).
  categoryHasScheduledTransfers,

  /// Перенос категории создал бы цикл в дереве.
  categoryCycle,

  /// Родительская категория недоступна: не найдена или другого вида.
  parentInvalid,

  /// Бюджет можно установить только на категорию расходов.
  budgetCategoryInvalid,

  /// У категории уже есть живой бюджет — второго не бывает.
  budgetAlreadyExists,

  /// Файловая система недоступна (v6, D-63): каталог вложений не создать,
  /// файл не записать/не удалить. Операция в этом случае создаётся без
  /// вложения — отказ не должен терять данные пользователя.
  storageFailure,

  /// Всё остальное — unexpected.
  unknown,
}
